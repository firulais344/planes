// Renders the timeline model into ONE HyperFrames composition (composition/index.html).
// It previews in HyperFrames Studio and renders to MP4 with headless Chrome + FFmpeg.
import fs from "node:fs";
import path from "node:path";
import { SKILL_DIR, jobPath, writeJson } from "./job.mjs";
import { overlayHtml, overlayCss, fontFaceCss, svgDefs, FONT_FILES } from "./overlay-html.mjs";

export const HYPERFRAMES_VERSION = "0.9.30";
const GSAP = "https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js";

const n = (x) => String(Math.round(x * 1000) / 1000);
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const TRACK = { visual: 2, fx: 3, text: 4 };

export function renderCompositionHtml(m) {
  const W = m.width;
  const H = m.height;
  const hasVoice = Boolean(m.aroll.voice);
  // 12 ms edge fades on speech stop clicks at cut points without being audible as fades.
  const fade = 'data-fade-in="0.012" data-fade-out="0.012"';

  const aroll = m.segments
    .map((seg, k) => {
      const audio = hasVoice ? "muted" : `data-has-audio="true" ${fade}`;
      return `      <video id="a${k}" class="clip aroll" src="${esc(m.aroll.src)}" playsinline ${audio} data-start="${n(seg.o)}" data-duration="${n(seg.e - seg.s)}" data-media-start="${n(seg.s)}" data-track-index="0"></video>`;
    })
    .join("\n");

  const voice = hasVoice
    ? m.segments.map((seg, k) => `      <audio id="v${k}" src="${esc(m.aroll.voice)}" ${fade} data-start="${n(seg.o)}" data-duration="${n(seg.e - seg.s)}" data-media-start="${n(seg.s)}" data-track-index="1"></audio>`).join("\n")
    : "";

  const overlays = m.overlays
    .map((o) => {
      const attrs = [`data-start="${n(o.s)}"`, `data-duration="${n(o.e - o.s)}"`, `data-track-index="${TRACK[o.track] ?? 2}"`];
      if (o.kind === "video") attrs.push(`data-media-start="${n(o.mediaStart || 0)}"`);
      return `      ${overlayHtml(o, { attrs: attrs.join(" ") })}`;
    })
    .join("\n");

  const music = m.music
    ? `      <audio id="music" src="${esc(m.music.src)}" data-start="0" data-duration="${n(m.duration)}" data-volume="${m.music.volume}" data-fade-in="0.5" data-fade-out="${m.music.fadeOut}" data-track-index="5"></audio>`
    : "";
  const sfx = m.sfx.map((s, k) => `      <audio id="s${k}" src="${esc(s.src)}" data-start="${n(s.s)}" data-duration="${n(s.e - s.s)}" data-volume="${s.volume}" data-track-index="6"></audio>`).join("\n");

  // The only motion in the whole edit: the whip-pan between cinematic blocks. Text and images never animate.
  const tl = [];
  for (const o of m.overlays) {
    if (!o.whip) continue;
    tl.push(`tl.fromTo("#${o.id}-whipblur", { attr: { stdDeviation: "${Math.round(W * 0.06)} 0" } }, { attr: { stdDeviation: "0 0" }, duration: ${n(o.whip.seconds)}, ease: "power2.out" }, ${n(o.whip.at)});`);
    tl.push(`tl.fromTo("#${o.id}", { xPercent: 16, scale: 1.4 }, { xPercent: 0, scale: 1, duration: ${n(o.whip.seconds)}, ease: "power3.out" }, ${n(o.whip.at)});`);
  }
  tl.push(`tl.set({}, {}, ${n(m.duration)});`);

  return `<!doctype html>
<!-- Generated by 11 Second Edit (${m.styleName} style) from model.json. Re-generated on every edit; change the edit, not this file. -->
<html lang="en" data-resolution="${H > W ? "portrait" : "landscape"}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <script src="${GSAP}"></script>
    <style>
${fontFaceCss("fonts/")}
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: ${W}px; height: ${H}px; overflow: hidden; background: #000; }
      #root { position: relative; width: ${W}px; height: ${H}px; overflow: hidden; }
      .aroll { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; z-index: 1;${m.aroll.css ? ` filter: ${m.aroll.css};` : ""} }
${overlayCss("#root")}
    </style>
  </head>
  <body>
    ${svgDefs(m)}
    <div id="root" data-composition-id="main" data-start="0" data-duration="${n(m.duration)}" data-fps="${m.fps}" data-width="${W}" data-height="${H}">
${[aroll, voice, overlays, music, sfx].filter(Boolean).join("\n")}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      ${tl.join("\n      ")}
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
}

/** Link (or copy) a job file into the composition folder; the original is never written to. */
function linkInto(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  try {
    const a = fs.statSync(src);
    const b = fs.statSync(dest);
    if (a.ino === b.ino || (a.size === b.size && b.mtimeMs >= a.mtimeMs)) return;
    fs.rmSync(dest);
  } catch {}
  try {
    fs.linkSync(src, dest);
  } catch {
    fs.copyFileSync(src, dest);
  }
}

export function writeComposition(id, model) {
  const dir = jobPath(id, "composition");
  fs.mkdirSync(dir, { recursive: true });
  const media = new Set([model.aroll.src, model.aroll.voice, model.music?.src, ...model.overlays.map((o) => o.src), ...model.sfx.map((s) => s.src)].filter(Boolean));
  for (const rel of media) linkInto(jobPath(id, rel), path.join(dir, rel));
  for (const [, , , file] of FONT_FILES) linkInto(path.join(SKILL_DIR, "assets", "fonts", file), path.join(dir, "fonts", file));
  fs.writeFileSync(path.join(dir, "index.html"), renderCompositionHtml(model));
  writeJson(path.join(dir, "meta.json"), { id: `11se-${id}`, name: `11 Second Edit ${id}` });
  writeJson(path.join(dir, "hyperframes.json"), {
    $schema: "https://hyperframes.heygen.com/schema/hyperframes.json",
    paths: { blocks: "compositions", components: "compositions/components", assets: "media" },
    media: { autoProxy: true },
  });
  writeJson(path.join(dir, "package.json"), {
    name: `11se-${id}`,
    private: true,
    type: "module",
    scripts: {
      dev: `npx --yes hyperframes@${HYPERFRAMES_VERSION} preview`,
      check: `npx --yes hyperframes@${HYPERFRAMES_VERSION} check`,
      render: `npx --yes hyperframes@${HYPERFRAMES_VERSION} render`,
    },
  });
  return path.join(dir, "index.html");
}
